# -*- coding: utf-8 -*-
"""Simulation dataset validator.

The validator loads a run manifest (generated by ``simulation_recorder``) and the
corresponding trajectory JSONL file.  It checks that the JSON objects contain the
required top‑level fields and that timestamps are strictly increasing within a
run.

The function ``validate_run`` returns a dictionary compatible with the existing
validation format used in :pymod:`genevac.prediction.dataset_pipeline` – i.e.
``{"valid": bool, "errors": list[str]}``.
"""

import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

REQUIRED_FIELDS = {
    "run_id",
    "dataset",
    "scene",
    "timestamp",
    "agent_id",
    "x",
    "y",
}

# Fields required by the new TrajectoryRecord schema (produced by simulation_recorder)
_REQUIRED_TRAJ_FIELDS = (
    "run_id", "scenario_id", "layout_id", "pedestrian_id",
    "step_index", "timestamp", "x", "y", "category",
)


def _load_manifest(manifest_path: Path) -> Dict[str, Any]:
    """Load the JSON manifest produced by :pymod:`simulation_recorder`.

    The manifest is a small JSON object; we only need a few keys for validation.
    """
    with manifest_path.open(encoding="utf-8") as f:
        return json.load(f)


def _load_trajectory_file(trajectory_path: Path) -> List[Dict[str, Any]]:
    """Read a JSONL file where each line is a trajectory observation.

    Returns a list of dictionaries – one per observation.
    """
    observations: List[Dict[str, Any]] = []
    with trajectory_path.open(encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                observations.append(json.loads(line))
            except json.JSONDecodeError as exc:
                raise ValueError(f"{trajectory_path}:{line_no}: invalid JSON – {exc}")
    return observations


def validate_run(manifest_path: str | Path) -> Dict[str, Any]:
    """Validate a single simulation run.

    Parameters
    ----------
    manifest_path:
        Path to the ``*_manifest.json`` file written by the recorder.

    Returns
    -------
    dict
        ``{"valid": bool, "errors": list[str]}``
    """
    manifest_path = Path(manifest_path)
    manifest = _load_manifest(manifest_path)

    trajectory_path = Path(manifest.get("trajectory_file", ""))
    if not trajectory_path.is_file():
        return {"valid": False, "errors": [f"trajectory file not found: {trajectory_path}"]}

    observations = _load_trajectory_file(trajectory_path)
    errors: List[str] = []
    prev_ts: float | None = None

    for idx, obs in enumerate(observations):
        missing = REQUIRED_FIELDS - obs.keys()
        if missing:
            errors.append(f"observation {idx}: missing fields {sorted(missing)}")
            continue

        # numeric sanity checks
        try:
            ts = float(obs["timestamp"])
            x = float(obs["x"])
            y = float(obs["y"])
        except (TypeError, ValueError):
            errors.append(f"observation {idx}: non‑numeric timestamp/x/y")
            continue

        if not all(math.isfinite(v) for v in (ts, x, y)):
            errors.append(f"observation {idx}: non‑finite values")
            continue

        if prev_ts is not None and ts <= prev_ts:
            errors.append(f"observation {idx}: non‑increasing timestamp {ts} <= {prev_ts}")
        prev_ts = ts

    return {"valid": not errors, "errors": errors}


def validate_dataset(
    manifests_dir: Path,
    *,
    min_trajectory_length: int = 2,
) -> Dict[str, Any]:
    """Validate all runs in *manifests_dir* and return a quality report dict."""
    from genevac.data.simulation.manifest import list_manifests, load_manifest

    manifests = list_manifests(manifests_dir)
    errors: List[Dict[str, Any]] = []
    warnings: List[Dict[str, Any]] = []
    total_records = 0
    invalid_records = 0
    valid_runs = 0
    invalid_runs = 0
    affected_runs: Set[str] = set()
    affected_peds: Set[str] = set()

    for mpath in manifests:
        try:
            manifest = load_manifest(mpath)
        except Exception as exc:
            errors.append({"run_id": str(mpath.stem), "error": f"Cannot load manifest: {exc}"})
            invalid_runs += 1
            continue

        run_id = str(manifest.get("run_id", "UNKNOWN"))
        traj_file_str = manifest.get("trajectory_file")
        if not traj_file_str:
            errors.append({"run_id": run_id, "error": "manifest missing trajectory_file"})
            invalid_runs += 1
            affected_runs.add(run_id)
            continue

        traj_file = Path(traj_file_str)
        if not traj_file.is_file():
            errors.append({"run_id": run_id, "error": f"trajectory_file not found: {traj_file}"})
            invalid_runs += 1
            affected_runs.add(run_id)
            continue

        run_errors: List[str] = []
        ped_last_ts: Dict[str, float] = {}
        ped_obs_count: Dict[str, int] = defaultdict(int)
        seen_keys: Set[Tuple[str, str, Any]] = set()

        with traj_file.open("r", encoding="utf-8") as fh:
            for lineno, raw in enumerate(fh, 1):
                raw = raw.strip()
                if not raw:
                    continue
                total_records += 1
                try:
                    rec = json.loads(raw)
                except json.JSONDecodeError as exc:
                    run_errors.append(f"line {lineno}: invalid JSON – {exc}")
                    invalid_records += 1
                    continue

                missing = [f for f in _REQUIRED_TRAJ_FIELDS if f not in rec]
                if missing:
                    run_errors.append(f"line {lineno}: missing fields {missing}")
                    invalid_records += 1
                    continue

                rec_run_id = str(rec["run_id"]).strip()
                ped_id = str(rec["pedestrian_id"]).strip()
                if not rec_run_id or rec_run_id != run_id:
                    run_errors.append(f"line {lineno}: run_id mismatch ({rec_run_id!r} != {run_id!r})")
                    invalid_records += 1
                    continue
                if not ped_id:
                    run_errors.append(f"line {lineno}: empty pedestrian_id")
                    invalid_records += 1
                    continue

                step = rec["step_index"]
                ts = rec["timestamp"]
                x = rec["x"]
                y = rec["y"]

                if not isinstance(step, int) or isinstance(step, bool) or step < 0:
                    run_errors.append(f"line {lineno}: invalid step_index {step!r}")
                    invalid_records += 1
                    continue

                bad_num = False
                for name, val in (("x", x), ("y", y), ("timestamp", ts)):
                    if not isinstance(val, (int, float)) or isinstance(val, bool) or not math.isfinite(val):
                        run_errors.append(f"line {lineno}: {name}={val!r} is not finite")
                        invalid_records += 1
                        bad_num = True
                        break
                if bad_num:
                    continue

                for fname in ("vx", "vy", "speed"):
                    fval = rec.get(fname)
                    if fval is not None and (
                        not isinstance(fval, (int, float)) or isinstance(fval, bool) or not math.isfinite(fval)
                    ):
                        warnings.append({"run_id": run_id, "warning": f"line {lineno}: {fname}={fval!r} non-finite, ignored"})

                key = (run_id, ped_id, step)
                if key in seen_keys:
                    run_errors.append(f"line {lineno}: duplicate record for ped={ped_id} step={step}")
                    invalid_records += 1
                    continue
                seen_keys.add(key)

                if ped_id in ped_last_ts and ts <= ped_last_ts[ped_id]:
                    run_errors.append(
                        f"line {lineno}: non-monotonic timestamp for ped={ped_id}: {ts} <= {ped_last_ts[ped_id]}"
                    )
                    invalid_records += 1
                    continue

                ped_last_ts[ped_id] = float(ts)
                ped_obs_count[ped_id] += 1

        for ped_id, count in ped_obs_count.items():
            if count < min_trajectory_length:
                warnings.append({
                    "run_id": run_id,
                    "warning": f"pedestrian {ped_id} has only {count} observation(s) (min={min_trajectory_length})",
                })
                affected_peds.add(ped_id)

        if run_errors:
            invalid_runs += 1
            affected_runs.add(run_id)
            for e in run_errors:
                errors.append({"run_id": run_id, "error": e})
        else:
            valid_runs += 1

    valid_records = total_records - invalid_records
    return {
        "schema_version": "v1",
        "total_runs": len(manifests),
        "valid_runs": valid_runs,
        "invalid_runs": invalid_runs,
        "total_records": total_records,
        "valid_records": valid_records,
        "invalid_records": invalid_records,
        "warning_count": len(warnings),
        "errors": errors,
        "warnings": warnings,
        "affected_run_ids": sorted(affected_runs),
        "affected_pedestrian_ids": sorted(affected_peds),
    }


def write_quality_report(report: Dict[str, Any], dest: Path) -> None:
    """Serialise *report* to a JSON file at *dest*."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(report, indent=2), encoding="utf-8")
